"""Формат работы: удалёнка, офис или молчание.

Владелец рассматривает только удалённый формат — страна значения не имеет.
Задача модуля — не пропустить в отклики офисные вакансии и вакансии «с
помощью в релокации», не выбросив при этом всё остальное.

Трёхзначный ответ, а не булев, потому что данные трёхзначные. Замер по 4395
собранным вакансиям: 51% пишут про удалёнку прямо, 9% пишут только про офис,
11% упоминают оба формата и 29% не говорят ничего.

Отсюда правила:

  «удалёнка + офис» — это НЕ офис. Живые примеры из базы: «Формат работы:
  Удалённо/Гибрид/Офис», «Удаленная работа полностью или гибридный вариант,
  Барселона». Удалёнку предлагают, выбор за кандидатом. Резать такое значило
  бы выбросить 493 подходящие вакансии ради 397 неподходящих.

  Молчание — не офис. 1261 вакансия просто не указывает формат; часть из них
  удалённые. Их не режем, но письмо само называет ограничение первой строкой:
  если формат не совпал, рекрутёр не ответит, и контакт не потрачен впустую.

  Офис без единого упоминания удалёнки — отказ. Проверено на выборке: это
  «Формат работы: в офисе (м. Павелецкая)» и «Помогают с релокацией
  (Сингапур)», то есть ровно то, что владельцу не подходит.
"""
from __future__ import annotations

import re

REMOTE = "remote"
ONSITE = "onsite"
UNKNOWN = "unknown"

# Кириллица: только формы про ФОРМАТ РАБОТЫ, а не любое «удалённ*».
# Проверено аудитом на живых текстах: «настройка удалённого доступа к
# серверам» и «работа с удалёнными филиалами» — офисные обязанности
# сисадмина, но старая основа «удал\w*» превращала их в REMOTE, и офисная
# вакансия проходила фильтр отбора.
_REMOTE_RE = re.compile(
    r"(удал[ёе]нн(?:ая|ой|ую)\s+работ\w*|удал[ёе]нн(?:ый|ого|ом)\s+формат\w*|"
    r"работ\w*\s+удал[ёе]нн\w*|полностью\s+удал[ёе]нн\w*|удал[ёе]нно\b|"
    r"удал[ёе]нк\w*|из\s+дома|"
    r"\bremote\b|remote[-\s]?(?:first|friendly|ok|work)|fully\s+remote|"
    r"work\s+from\s+home|\bwfh\b|distributed\s+team|work\s+from\s+anywhere)",
    re.I)

# Явное отрицание удалёнки: «Remote: No», «no remote», «удалёнки нет».
# Содержит слово remote, поэтому проверяется РАНЬШЕ позитивного паттерна.
_REMOTE_NEG_RE = re.compile(
    r"(?:\bno\s+remote\b|\bnot\s+(?:a\s+)?remote\b|remote\s*:\s*no\b|"
    r"remote\s+(?:work\s+)?(?:is\s+)?not\s+(?:possible|available|an?\s+option)|"
    r"без\s+удал[ёе]нк\w*|удал[ёе]нк\w*\s+не(?:т\b|возможн\w*)|"
    r"удал[ёе]нн\w*\s+работ\w*\s+не\s+(?:предусмотрен\w*|предполагает\w*|"
    r"рассматрива\w*|возможн\w*)|"
    r"удал[ёе]нно\s+нельзя)", re.I)

# «Помогают с релокацией» — тоже офис: переезд ради работы противоположен
# удалёнке, даже когда звучит как льгота.
_ONSITE_RE = re.compile(
    r"(гибрид\w*|\bhybrid\b|офис\w*|"
    r"on[-\s]?site|\bonsite\b|присутстви\w+\s+в\s+офисе|"
    r"переезд\w*|релокац\w*|relocation)", re.I)


def detect(*parts: str) -> str:
    """REMOTE / ONSITE / UNKNOWN по тексту вакансии."""
    text = " ".join(p or "" for p in parts)
    if _REMOTE_NEG_RE.search(text):
        return ONSITE
    if _REMOTE_RE.search(text):
        return REMOTE
    if _ONSITE_RE.search(text):
        return ONSITE
    return UNKNOWN
